var currentLang = 'vi';
var translations = _phTranslationsData;

function getTranslation(key) {
  var keys = key.split('.');
  var value = translations[currentLang];
  for (var i = 0; i < keys.length; i++) {
    value = value && value[keys[i]];
    if (value === undefined) return key;
  }
  return value;
}

function updatePage() {
  /* textContent replacements */
  var i18nEls = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < i18nEls.length; i++) {
    var el = i18nEls[i];
    var key = el.getAttribute('data-i18n');
    var text = getTranslation(key);
    if (text) el.textContent = text;
  }

  /* attribute replacements: data-i18n-label → data-label, etc. */
  var attrEls = document.querySelectorAll('[data-i18n-label]');
  for (var j = 0; j < attrEls.length; j++) {
    var ael = attrEls[j];
    var akey = ael.getAttribute('data-i18n-label');
    var atext = getTranslation(akey);
    if (atext) ael.setAttribute('data-label', atext);
  }

  /* aria-label replacements */
  var ariaEls = document.querySelectorAll('[data-i18n-aria]');
  for (var k = 0; k < ariaEls.length; k++) {
    var arel = ariaEls[k];
    var arkey = arel.getAttribute('data-i18n-aria');
    var artext = getTranslation(arkey);
    if (artext) arel.setAttribute('aria-label', artext);
  }

  /* alt attribute replacements */
  var altEls = document.querySelectorAll('[data-i18n-alt]');
  for (var m = 0; m < altEls.length; m++) {
    var altel = altEls[m];
    var altkey = altel.getAttribute('data-i18n-alt');
    var alttext = getTranslation(altkey);
    if (alttext) altel.setAttribute('alt', alttext);
  }

  /* title attribute replacements */
  var titleEls = document.querySelectorAll('[data-i18n-title]');
  for (var n = 0; n < titleEls.length; n++) {
    var titleEl = titleEls[n];
    var titleKey = titleEl.getAttribute('data-i18n-title');
    var titleText = getTranslation(titleKey);
    if (titleText) titleEl.setAttribute('title', titleText);
  }

  /* placeholder attribute replacements */
  var placeholderEls = document.querySelectorAll('[data-i18n-placeholder]');
  for (var p = 0; p < placeholderEls.length; p++) {
    var placeholderEl = placeholderEls[p];
    var placeholderKey = placeholderEl.getAttribute('data-i18n-placeholder');
    var placeholderText = getTranslation(placeholderKey);
    if (placeholderText) placeholderEl.setAttribute('placeholder', placeholderText);
  }

  updateMetaTags();
  updateLangButton();
}

